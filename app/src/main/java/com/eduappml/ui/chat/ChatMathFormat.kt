package com.eduappml.ui.chat

/**
 * Приводит LaTeX-разметку из ответа чата к единственному формату, который
 * надёжно рендерит [com.eduappml.ui.common.MarkdownText] — блочный "$$" на
 * отдельной строке, с пустыми строками до и после (см. MarkdownText.kt).
 *
 * GigaChat может присылать формулы в разных обозначениях:
 * "\[ ... \]" и "\( ... \)" (LaTeX display/inline math), "$$ ... $$" в одну
 * строку, а также одиночный инлайн "$ ... $" внутри предложения — судя по
 * практике, именно одиночный "$...$" GigaChat использует чаще всего для
 * коротких формул внутри текста, и именно этот случай раньше не обрабатывался
 * вовсе (отсюда была замечена проблема: собственный вопрос пользователя
 * отображался правильно — он собирается из уже блочно оформленного текста
 * .md-файлов — а ответ модели, использующий свой инлайн-стиль, не отображался).
 *
 * ВАЖНО про порядок обработки: сначала все формулы (из любого формата)
 * вырезаются во временные плейсхолдеры (управляющий символ \u0000 практически
 * никогда не встречается в реальном тексте), и только потом возвращаются на
 * место в едином блочном виде. Без этого более поздний проход (одиночный $)
 * рисковал бы залезть внутрь уже вставленных нами служебных "$$" — именно
 * так когда-то в этом проекте сломалась normalizeMathDelimiters() в
 * MarkdownText.kt, поэтому здесь применён принципиально другой, безопасный
 * порядок операций.
 *
 * Известное ограничение: если в ответе встретятся два отдельных, не связанных
 * друг с другом одиночных "$" (например, упоминание цены "$5 ... $10"), они
 * могут быть ошибочно приняты за пару формулы. Учитывая, что эта функция
 * работает только в контексте объяснения математических формул (кнопка
 * "Объяснить в чате" открывается с экранов Теории/Математики/Кода), такой
 * случай маловероятен на практике, а его последствие — не поломка, а просто
 * фрагмент текста, визуально оформленный как формула.
 */
fun normalizeChatMath(raw: String): String {
    val formulas = mutableListOf<String>()
    var text = raw

    fun extract(pattern: Regex, input: String): String =
        pattern.replace(input) { m ->
            formulas.add(m.groupValues[1].trim())
            "\u0000${formulas.size - 1}\u0000"
        }

    // Порядок важен: сначала backslash-обозначения (синтаксически уникальны,
    // никак не пересекаются с "$"), затем "$$...$$", и только в самом конце —
    // одиночный "$...$". К моменту последнего прохода все "$$" уже вырезаны
    // в плейсхолдеры, поэтому одиночный "$" не может случайно оказаться
    // внутри них.
    text = extract(Regex("""\\\[([\s\S]*?)\\\]"""), text)   // \[ ... \]
    text = extract(Regex("""\\\(([\s\S]*?)\\\)"""), text)   // \( ... \)
    text = extract(Regex("""\$\$([\s\S]*?)\$\$"""), text)   // $$ ... $$
    text = extract(Regex("""\$([^$\n]+?)\$"""), text)        // одиночный $ ... $ (без переноса строки внутри)

    formulas.forEachIndexed { i, formula ->
        text = text.replace("\u0000$i\u0000", "\n\n\$\$\n$formula\n\$\$\n\n")
    }

    // Подчистка: 3+ переноса подряд -> ровно один пустая строка. Не убирает
    // пустые строки целиком (в отличие от старой normalizeMathDelimiters()) —
    // просто убирает лишний избыток, минимально необходимое для блочного
    // формата (одна пустая строка до и после "$$") остаётся на месте.
    text = Regex("""\n{3,}""").replace(text, "\n\n")

    return text.trim()
}
