package com.eduappml.ui.common

import androidx.compose.runtime.Composable
import androidx.compose.ui.graphics.drawscope.DrawScope
import androidx.compose.ui.platform.LocalConfiguration
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp
import kotlin.math.min

/**
 * ЕДИНАЯ точка настройки адаптивности интерфейса.
 *
 * Зачем это нужно. Исторически весь UI рисовался под один телефон:
 *  - размеры компоновки заданы в dp (это правильно — dp не зависит от плотности);
 *  - НО размеры внутри Canvas задавались сырыми пикселями (`strokeWidth = 2f`,
 *    `radius = 5f`). Пиксель — не единица длины: на mdpi-экране (density 1.0)
 *    линия в 2px физически втрое толще, чем на xxhdpi (density 3.0). Отсюда
 *    эффект «на одном телефоне красиво, на другом мутно и мелко»;
 *  - и размеры не масштабировались под площадь экрана: на планшете холст
 *    вырастает в 2–2.5 раза, а пузыри остаются прежними — редкие точки в пустоте.
 *
 * Оба перекоса лечатся отсюда, не трогая логику экранов.
 */
object Adaptive {

    /**
     * Минимальная сторона экрана, под которую исторически подбиралась раскладка
     * (обычный телефон в портрете — 360dp по ширине). Всё, что мы масштабируем,
     * масштабируется относительно этого эталона.
     */
    val ReferenceMinSide: Dp = 360.dp

    /**
     * Плотность экрана, на которой подбирались «пиксельные» константы отрисовки.
     * 2.75 — это ~440dpi, типичный современный телефон среднего/верхнего сегмента.
     *
     * ЕСЛИ интерфейс изначально доводился на другом устройстве — поправьте здесь
     * одно число, и все Canvas-константы приложения пересчитаются согласованно.
     * Проверить плотность своего устройства: `adb shell wm density`
     * (значение / 160 = density).
     */
    const val ReferenceDensity: Float = 2.75f

    /**
     * Комфортная максимальная ширина колонки текста. Длинная строка на планшете
     * читается плохо: глазу тяжело возвращаться к началу следующей строки.
     * Полиграфический ориентир — 60–75 символов, для кириллицы при 16sp это
     * примерно 600–660dp.
     */
    val ContentMaxWidth: Dp = 640.dp

    /**
     * Максимальная ширина форм — вход, регистрация, подтверждение почты.
     * Уже, чем колонка текста: поле ввода шириной во весь планшет выглядит
     * нелепо и заставляет глаз ехать от подписи слева к курсору справа.
     * 420dp — примерно ширина телефона, к которой все привыкли в формах.
     */
    val FormMaxWidth: Dp = 420.dp

    /** Границы масштабирования графики: ниже — мелко, выше — карикатурно крупно. */
    const val ScaleMin: Float = 0.9f
    const val ScaleMax: Float = 1.7f
}

/**
 * Коэффициент масштабирования графики для экрана с минимальной стороной [minSide].
 *
 * Считается именно от МЕНЬШЕЙ стороны, а не от площади и не от ширины:
 *  - телефон в портрете 360x740  -> min 360  -> 1.00 (эталон, ничего не меняется)
 *  - узкий телефон    320x640    -> min 320  -> 0.90
 *  - телефон в ландшафте 740x360 -> min 360  -> 1.00 (тоже ничего не меняется —
 *    и это правильно: по высоте места не прибавилось)
 *  - планшет 800x1280            -> min 800  -> 1.70 (упирается в потолок)
 */
fun uiScale(minSide: Dp): Float =
    (minSide / Adaptive.ReferenceMinSide).coerceIn(Adaptive.ScaleMin, Adaptive.ScaleMax)

/** Коэффициент масштабирования для текущего экрана целиком. */
@Composable
fun currentUiScale(): Float {
    val configuration = LocalConfiguration.current
    return uiScale(min(configuration.screenWidthDp, configuration.screenHeightDp).dp)
}

/**
 * Перевод «сырой пиксельной» константы отрисовки в плотностно-независимую.
 *
 * Используется как обёртка вокруг чисел, которые уже подобраны на глаз и менять
 * их пропорции не хочется: `strokeWidth = designPx(2f)` рисует ровно ту же
 * толщину, что и раньше на эталонном устройстве, но теперь эта толщина одинакова
 * физически на любом экране.
 *
 * Для нового кода лучше сразу писать `2.dp.toPx()` — это честнее и читается
 * лучше. `designPx` существует, чтобы перевести уже существующую отрисовку
 * без визуальных регрессий.
 */
fun DrawScope.designPx(value: Float): Float =
    value * (density / Adaptive.ReferenceDensity)
