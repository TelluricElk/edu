package com.eduappml.voice

/** Состояние голосовой сессии — на нём держится вся индикация в чате. */
enum class VoiceState {
    /** Режим выключен, сессии нет. */
    IDLE,

    /** Идёт подключение к релею и настройка сессии. */
    CONNECTING,

    /**
     * Сессия открыта, но микрофон закрыт: ждём нажатия кнопки или
     * напечатанного вопроса. Микрофон одноразовый — после каждой фразы
     * разговор возвращается сюда.
     */
    IDLE_SESSION,

    /** Микрофон открыт, слушаем реплику. */
    LISTENING,

    /** Ассистент отвечает — голосом или текстом. */
    SPEAKING,

    /** Сессия оборвалась с ошибкой. */
    ERROR
}
