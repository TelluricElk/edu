package com.eduappml.voice

/**
 * Настройки голосового режима Edu.AI (Yandex AI Studio Realtime).
 *
 * Ключ Яндекса здесь намеренно отсутствует: приложение ходит не в Яндекс,
 * а в собственный релей (`server/voice-relay/`), который держит ключ у себя.
 * Приложение предъявляет релею тот же Supabase-токен, что и остальному API.
 */
object VoiceConfig {

    /**
     * Адрес релея. Если на сервере перед Supabase стоит nginx с блоком
     * `location /voice` — оставляем без порта; иначе указываем порт 8787.
     * Схема `wss://`, как только на nginx появится TLS.
     */
    const val RELAY_URL = "ws://157.22.206.53:8787/voice"

    /** Частота записи с микрофона. Должна совпадать с CLIENT_IN_RATE релея. */
    const val MIC_SAMPLE_RATE = 16000

    /** Частота воспроизведения. Должна совпадать с CLIENT_OUT_RATE релея. */
    const val PLAYBACK_SAMPLE_RATE = 24000

    /** Размер куска записи в миллисекундах — компромисс между задержкой и числом кадров. */
    const val MIC_CHUNK_MS = 40

    // -----------------------------------------------------------------------
    // Таймеры микрофона
    // -----------------------------------------------------------------------
    // Поведение скопировано с голосового ввода в поиске Google: микрофон
    // одноразовый. Нажали — слушает одну фразу, сама фраза закончилась —
    // микрофон закрылся. Постоянно открытый микрофон в разговоре с озвучкой
    // работать не может: динамик попадает обратно в микрофон, модель слышит
    // себя и отвечает снова и снова.

    /** Сколько ждём НАЧАЛА речи, прежде чем закрыть микрофон молча. */
    const val NO_SPEECH_TIMEOUT_MS = 7_000L

    /** Потолок длительности одной реплики — страховка от забытого микрофона. */
    const val MAX_PHRASE_MS = 30_000L
}
